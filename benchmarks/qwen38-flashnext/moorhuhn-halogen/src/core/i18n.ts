const dictionaries: Record<Lang, Dict> = { de, en };

/** Allow content modules to register their own translation keys at load time. */
export function addTranslations(lang: Lang, dict: Dict): void {
  Object.assign(dictionaries[lang], dict);
}

let currentLang: Lang = 'de';

export function setLanguage(lang: Lang): void {
  currentLang = dictionaries[lang] ? lang : 'de';
}

export function getLanguage(): Lang {
  return currentLang;
}

/** Pick the browser language with German as fallback. */
export function detectLanguage(): Lang {
  const nav = typeof navigator !== 'undefined' ? (navigator.language ?? 'de') : 'de';
  return nav.toLowerCase().startsWith('en') ? 'en' : 'de';
}

export function translate(key: string, vars?: Record<string, string | number>, lang: Lang = currentLang): string {
  const dict = dictionaries[lang] ?? de;
  let str = dict[key];
  if (str === undefined) str = de[key];
  if (str === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

/** Convenience proxy: `t('menu.play')` in current language. */
export const t = translate;

/** True when a key resolves in a specific language (used by fallback tests). */
export function hasKey(key: string, lang: Lang): boolean {
  return dictionaries[lang]?.[key] !== undefined;
}

export function keyCount(lang: Lang): number {
  return Object.keys(dictionaries[lang] ?? {}).length;
}
