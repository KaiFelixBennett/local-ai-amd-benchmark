export type Dict = Record<string, string>;
export const dicts: Record<Lang, Dict> = { de: DE, en: EN };

/**
 * Translate `key` into `lang` with {placeholder} interpolation.
 * Falls back to German, then to 'de.<key>', so a translation miss is visible but never crashes.
 */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? dicts.de[key] ?? `de.${key}`;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

let activeLang: Lang = 'de';

export function currentLang(): Lang {
  try {
    return resolveLanguage(getSettings().language);
  } catch {
    return activeLang;
  }
}

export function setLang(l: Lang): void {
  activeLang = l;
}

/** t() bound to the currently configured language. */
export function t(key: string, vars?: Record<string, string | number>): string {
  return translate(currentLang(), key, vars);
}

