export type StringKey = keyof (typeof STRINGS)['de'];

export function detectLang(): Lang {
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language : 'de';
    return nav.toLowerCase().startsWith('en') ? 'en' : 'de';
  } catch {
    return 'de';
  }
}

let currentLang: Lang = detectLang();

export function setLang(lang: Lang): void {
  currentLang = lang;
  window.dispatchEvent(new CustomEvent('mm-lang-changed', { detail: { lang } }));
}

export function getLang(): Lang {
  return currentLang;
}

/**
 * Übersetzt einen Key. Fallback: englisch, dann der Key selbst.
 * {placeholders} werden durch params ersetzt.
 */
export function t(key: StringKey, params?: Record<string, string | number>): string {
  let s: string | undefined = STRINGS[currentLang][key];
  if (s === undefined) s = STRINGS.de[key] ?? STRINGS.en[key];
  if (s === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/**
 * Übersetzt einen dynamisch zusammengesetzten Key (z. B. `target.${id}`).
 * Fallback wie bei `t`: deutsch → englisch → Key selbst.
 */
export function tRaw(key: string, params?: Record<string, string | number>): string {
  const table = (lang: Lang): Record<string, string | undefined> =>
    STRINGS[lang] as unknown as Record<string, string | undefined>;
  let s: string | undefined = table(currentLang)[key];
  if (s === undefined) s = table('de')[key] ?? table('en')[key];
  if (s === undefined) return key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
